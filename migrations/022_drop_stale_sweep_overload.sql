--
-- ⛔⛔ **מה הקובץ עושה:** ⚠️ גורע את `bk_retention_sweep(integer)` —
--    ⭐ עומס-יתר בן ארגומנט אחד שקדם לגרסת שלושת הארגומנטים, ⛔ ומיישר
--    את פקודת ה-`cron` לצורה המפורשת.
--
-- ⛔⛔ **הנימוק — נמדד ולא שוער:** ⚠️ ההסבה כתבה מחדש את גרסת שלושת
--    הארגומנטים בלבד, ⛔ והישנה נשארה נוקבת ב-`kv_backup` וב-`sync_log`
--    שכבר אינן קיימות: ⭐ ומעבר לכך, `bk_retention_sweep(30)` הפך
--    **דו-משמעי** — ⚠️ שתי החתימות תואמות לו, ⛔ ופוסטגרס מסרב לבחור.
--
-- ⛔ **ולכן הפינוי הלילי ב-03:00 היה נופל** — ⚠️ בשקט, ⭐ בדיוק הכשל
--    שהמנגנון הזה נבנה כדי למנוע.
--
-- ⛔ **ואין כאן מחיקת נתונים** — ⚠️ הגרעה היא של הגדרה שאין לה מסלול
--    ריצה תקף, ⭐ והטבלאות שהיא נוקבת בהן אינן קיימות.
--
-- ============================================================================

drop function if exists public.bk_retention_sweep(integer);

-- ⛔ הפקודה מיושרת לצורה המפורשת — ⚠️ כמו בפרויקט המשותף, ⭐ ולא
--    נשענת על ערכי ברירת המחדל שבחתימה.

select cron.alter_job(
  (select jobid from cron.job where command like '%bk_retention_sweep%'),
  command => 'select public.bk_retention_sweep(30, 7, 14);');
