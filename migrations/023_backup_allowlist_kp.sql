-- ⛔ **רצה במסד** — ⚠️ הוחלה בסבב 145 ואומתה מול `bk_retention_keys()`.
--
-- ⛔ `bk_retention_sweep` מפנה **רק** מפתחות שברשימת-ההיתר — ⚠️ ומפתח
--    שאינו בה אינו מתפנה לעולם: ⭐ טבלאות «הקופה» היו נצברות ב-`sh_backup`
--    בלי גבול.
--
-- ⛔ והרשימה נקראת מהמסד ⛔ ולא מקובץ המיגרציה — ⚠️ קובץ מודד את מה
--    שהוצהר ⛔ ולא את מה שרץ.
--
-- ⛔ והפונקציה בבעלות הריפו הזה ⛔ ובו בלבד — ⚠️ היא משרתת יותר
--    מאפליקציה אחת באותו פרויקט, ⭐ ועותק שני הוא מקור אמת שני שמתיישן.
--
-- ⚠️ והשמות מפורשים ⛔ ולא קידומת — ⭐ קידומת `kp_` הייתה תופסת גם גיבוי
--    `PRE_*` עתידי, שאין למחקו לעולם.
-- ==========================================================================
create or replace function public.bk_retention_keys()
returns text[]
language sql
immutable
as $function$
  select array[
    'g_donors', 'g_pledges', 'g_txns', 'g_tasks',
    'g_targets', 'g_config', 'g_users',
    'kp_settings', 'kp_years', 'kp_months', 'kp_standing_orders',
    'kp_so_instances', 'kp_entries', 'kp_lookups'
  ]::text[];
$function$;
