-- ============================================================================
--
-- ⛔ **שני הצעדים רצו במסד.** ⚠️ נמדד בסבב 91: העמודה **אינה קיימת עוד** —
--    ⭐ צעד ב הורץ. ⛔ מיגרציה שכבר רצה אינה נערכת.
--
-- ⭐ **מה שהוליד אותה:** `g_users.password` החזיקה טקסט גלוי,
--    ו-`doLogin` השווה `String(u.password) !== String(password)`. כלומר
--    היא הייתה **המפתח שפותח את הכניסה** — ו-RLS כאן הוא
--    `using (true) with check (true)` בכוונה מתועדת, עם GRANT ל-`anon`
--    ומפתח anon שיושב ב-`index.html` הציבורי.
--
-- ⚠️ **וזו הייתה החלטה מתועדת, לא פספוס.** פרק «מודל הסיסמאות» כאן קבע
--    במפורש שהטקסט הגלוי הוא בחירה תפעולית של המנהל — «לראות ולנהל
--    סיסמאות מתוך האפליקציה» — וכלל ברזל 9 מייחד את ההכרעה לו בלבד.
-- ⭐ **ההחלטה בוטלה על ידו**.
--
-- ⭐ **מה שכבר נעשה בקוד:** `doLogin` ומסך שינוי הסיסמה העצמי
--    מאמתים מול `pass_salt`+`pass_fp` דרך `gVerifyOffline`, ו-`passFields`
--    כותבת את הטקסט הגלוי אך ורק כל עוד `G_PLAINTEXT_LEGACY_WRITE` פתוח.
-- ⚠️ לפני הכתיבה נבדק ש: המשתמש היחיד
--    ב-`g_users` מחזיק מלח וטביעה באורך 64 — אף אחד לא ננעל בחוץ.
--
-- ═══ שני הצעדים, ו⛔ למה אסור לאחד אותם ═══════════════════════════════════
-- `password` היא `NOT NULL` בלי `DEFAULT`, ו-`writeUser` **כן** יוצרת
-- משתמשים כאן (בניגוד ל-schar-limud). לכן:
--
--   צעד א (למטה) — הסרת `NOT NULL`. בטוח להרצה **עכשיו**.
--
--   צעד ב (מוער) — מחיקת העמודה. ⛔ **רק אחרי** ש-`G_PLAINTEXT_LEGACY_WRITE`
--   כובה ונפרס, ואחרי שאומת שכניסה, יצירת משתמש ושינוי סיסמה עובדים.
-- ⛔ הכיבוי והמחיקה בסבבים נפרדים — אחרת אין חלון לגלות טעות.
--
-- ⚠️ **ומחיקת העמודה אינה מסירה את מה שכבר נראה:** ⛔ `g_users` נגבית
-- ל-`kv_backup` ב-`cols` מפורש — יש לוודא ש-`password` אינו
--    ברשימה לפני ההרצה. ⭐ והטיפול המלא הוא **החלפת הסיסמה** של המשתמש,
--    פעולת מנהל, אחרי צעד ב.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── צעד א — הסרת NOT NULL (אידמפוטנטי, בטוח להרצה מיידית) ──────────────────
alter table public.g_users alter column password drop not null;

