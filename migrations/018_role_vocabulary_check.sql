--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **`admin` · `manager`, ואין שלישי:** ⚠️ המיגרציה שלפניה המירה את
--    `owner` ל-`admin`, ⭐ **וכאן ההמרה נעשית הצהרה:** ⛔ בלי אילוץ,
--    `owner` היה יכול לחזור בכתיבה הבאה, ⚠️ והקוד שכבר אינו מכיר אותו
--    היה שולל הרשאה ממי שהיה בעלים — ⭐ בשקט.
--
-- ⛔ נכשל-סגור בכל מקרה: ⚠️ כל מה שאינו `admin` בדיוק אינו מקבל גישה.
--
-- ⛔ אידמפוטנטית: ⚠️ האילוץ מוסר ונוצר מחדש באותו שם.
-- ============================================================================

alter table g_users drop constraint if exists g_users_role_check;

alter table g_users
  add constraint g_users_role_check
  check (role = any (array['admin'::text, 'manager'::text]));
