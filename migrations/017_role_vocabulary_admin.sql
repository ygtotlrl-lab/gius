-- 017_role_vocabulary_admin.sql — אוצר מילים אחד לתפקיד
-- ============================================================================
--
-- ⛔ **רץ במסד.**
--
-- ⛔⛔ **`owner` ⟵ `admin`:** ⚠️ שלוש האפליקציות שיש בהן כניסה השוו כל
--    אחת מול שם תפקיד משלה, ⭐ **והנימוק:** ⛔ שלושה אוצרות מילים לאותו
--    מושג הם שלוש הזדמנויות לטעות — ⚠️ בדיקה שהועתקה בין האפליקציות
--    משווה מול שם שאינו קיים ⛔ ונכשלת פתוח. ⭐ מעכשיו `admin` הוא
--    המורשה ו-`manager` מי שאינו.
--
-- ⚠️ **התווית שעל המסך לא השתנתה** — ⛔ «בעלים» היא מה שהמשתמש רואה,
--    ⭐ והשם הפנימי הוא מה שהקוד משווה: ⛔ שינוי התווית היה שינוי מוצר
--    ⚠️ ולא יישור אוצר מילים.
--
-- ⛔ אידמפוטנטית: ⚠️ הרצה שנייה אינה מוצאת `owner` ואינה משנה דבר.
-- ============================================================================

update g_users
   set role = 'admin',
       updated_at = updated_at
 where role = 'owner';
