-- ⛔ **רצה במסד** — ⚠️ הוחלה בסבב 94 ואומתה מול `has_function_privilege`.
--    ⛔ מיגרציה שכבר רצה אינה נערכת — שינוי נוסף הוא קובץ חדש.
--
-- ⭐ **בהחלטת המנהל.** ⛔ הפונקציה מחזירה **שמות מפתחות בלבד** — ⚠️ ולא
--    נתונים, ⭐ ו-`anon` כבר קורא את הנתונים עצמם מטבלאות האפליקציה:
--    ⛔ ההרחבה אינה חושפת דבר שלא היה חשוף.
--
-- ⛔⛔ **ומה שהיא קונה:** ⚠️ שער המסד קרא עד כאן את הרשימה **מקובץ
--    המיגרציה**, ⭐ כלומר מדד את מה ש**הוצהר** ולא את מה ש**רץ**:
--    ⛔ מיגרציה שנכתבה ולא רצה הייתה עוברת בשקט — ⚠️ וזו בדיוק הסחיפה
--    שהשורה באה לתפוס.
--
-- ⚠️ **וההרשאה היא `EXECUTE` בלבד** — ⛔ אין כאן `GRANT` על טבלה,
--    ⭐ והפונקציה `immutable` ואינה כותבת דבר.
-- ============================================================================

grant execute on function public.bk_retention_keys() to anon;
