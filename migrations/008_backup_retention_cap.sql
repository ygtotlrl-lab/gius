-- ⛔ **רץ במסד.** ⛔ מיגרציה שכבר רצה אינה נערכת — ⚠️ המסד החיל אותה,
--    ועריכה שלה יוצרת מצב שבו הקובץ מתאר משהו אחר ממה שרץ; ⛔ שינוי מבני
--    נעשה בקובץ הבא בתור.
--
-- ⭐ **הבעיה בפרויקט המשותף ולא כאן, ⚠️ וזה נרשם ולא
--    מוסתר:** שם `kv_backup` מחזיקה **486 שורות · 71MB · 55 מפתחות
--    ייחודיים** — תשעה עותקים בממוצע למפתח, והקיצוני שבהם
--    `ys_attend_sessions` עם **81 עותקים · 31MB**.
-- ⚠️ ב-gius הנפח היום זניח, ⛔ אבל
--    המנגנון זהה בית-לבית והכשל מבני ולא מקומי — מפתח שנשמר כמה פעמים
--    ביום מצטבר בלי גבול בכל פרויקט שבו הגריעה היא לפי זמן בלבד.
--    ⛔ ולכן המדיניות נכנסת כאן **באותו סבב** ולא «כשיצטבר» (כלל ברזל 14):
--    מנגנון בטיחות שקיים בפרויקט אחד בלבד הוא בדיוק «קיים רק באחת, בשקט».
--
-- ⚠️ **והסיבה מבנית ולא תקלה:** `bk_retention_sweep` שנוצרה ב-004 מוחקת
--    לפי **זמן בלבד** — `created_at < now() - 30 days`. ⛔ אין בה תקרת
--    עותקים, ולכן מפתח שנשמר כמה פעמים ביום מצטבר בלי שום גבול: שלושים
--    יום × כמה כתיבות ביום = עשרות עותקים חיים, כולם «צעירים» מ-30 יום
--    וכולם מחוץ להישג ידה של הגריעה. ⛔ הגיבוי הדיפרנציאלי שבמודול מקטין
--    את התדירות אך אינו מגביל את המצבור — ערך שמשתנה כל יום נכתב כל יום.
--
-- ⭐ **מה הקובץ הזה משנה — שלושה ערכים, וכלל ברזל 20 הוא מקור האמת שלהם:**
--      · **7**  — תקרת עותקים לכל מפתח ברשימת-ההיתר (`p_keep`)
--      · **30** — תפוגת גיבוי אוטומטי, כפי שהייתה (`p_days`)
--      · **14** — תפוגת גיבוי ידני בקידומת `pre-` (`p_manual_days`)
--    ⛔ שינוי אחד מהם כאן בלי לעדכן את כלל ברזל 20 מפיל את
--    `tools/test_round61_backup_policy.mjs` בארבעת הריפו.
--
-- ⛔ אידמפוטנטי לחלוטין: `create or replace function`, ו-`unschedule` לפני
--    `schedule` מחדש. אין כאן `insert`/`update` על נתוני אפליקציה, ואין
--    שינוי הרשאות מעבר למה ש-004 כבר קבע.
--
-- ⚠️ **`bk_retention_keys()` לא נגעה** — רשימת-ההיתר נשארת בדיוק כפי שהיא
--    ב-004. ⛔ הקובץ הזה משנה **מדיניות**, לא את מה שמותר לגעת בו.
-- ============================================================================


-- ───────────────────────────────────────────────────────────────────────────
-- 1. הגריעה — שלושה מסלולים, שלוש הגנות ישנות ושתי חדשות
-- ───────────────────────────────────────────────────────────────────────────
-- ⛔ **שלוש בדיקות השפיות של 004 נשארות כלשונן** — רשימת-היתר
--    ריקה · מפתח מוגן ברשימה · חלון קצר מ-7 ימים. ⛔ אין לגעת בהן: כל אחת
--    מהן מסרבת לרוץ במקום למחוק «לפי מה שיש», וזו ההגנה על נתוני גיבוי
--    שאין להם עותק שני.
--
-- ⛔⛔ **וההגנה על מפתח מוגן ברשימה אינה הגנה מפני תפוגה** — זו
--     הנקודה העדינה בקובץ. היא בודקת את **תוכן רשימת-ההיתר** ומסרבת לרוץ
--     אם `PRE_*` / `ORPHAN_*` / `pre-delete-*` נכנסו לשם בטעות. ⛔ מסלול
--     ג' שלמטה אינו נוגע ברשימת-ההיתר כלל — הוא מסנן את **הטבלה** לפי
--     קידומת — ולכן ההגנה נשארת שלמה ובתוקף. ⚠️ ומכאן גם המשמעות שיש
--     לרשום במפורש: גיבוי `pre-delete-…` **כן** מתפנה אחרי 14 יום, מפני
--     שהוא גיבוי ידני לכל דבר; מה שאסור הוא להכניס אותו לרשימת-ההיתר
--     ולתת לו להתפנות כשגרה בת 30 יום.
--
-- ⚠️ **`like 'pre-%'` תלוי-רישיות, וזה מכוון** — `PRE_SYNC_UNIFY_`,
--    `PRE_ROUND3B_` ו-`ORPHAN_` הם **רישיות גדולות**, ולכן אינם נתפסים
--    כאן ואינם מתפנים לעולם. ⛔ אין להחליף ב-`ilike` ואין להרחיב לקידומת
--    נוספת בלי החלטת מנהל — זו בדיוק הדרך שבה נקודת חזרה חד-פעמית נמחקת
--    בשקט. ⚠️ ו-`-` אינו תו-הצבה ב-LIKE, ולכן אין מה לברוח כאן.
--
-- ⭐ **שתי הגנות חדשות, ומאותו דפוס בדיוק**: `p_keep < 1` היה
--    מוחק **את כל** העותקים של כל מפתח ברשימת-ההיתר, ו-`p_manual_days < 7`
--    היה מוחק גיבוי ידני שנוצר הרגע — כלומר בדיוק לפני הפעולה שהוא בא
--    להגן עליה. ⛔ שתיהן מסרבות לרוץ ואינן «מתקנות» את הערך.
-- ⛔⛔ **החתימה הישנה נמחקת קודם — ⚠️ והסדר הזה אינו סגנוני**:
--     ב-Postgres החתימה היא חלק מזהות הפונקציה, ולכן הפונקציה שלמטה היא
--     `bk_retention_sweep(integer, integer, integer)` — **פונקציה חדשה**,
--     שאינה מחליפה את `bk_retention_sweep(integer)` של 004 אלא חיה לצידה.
--     ⛔ ואז `select bk_retention_sweep(30)` נעשית **דו-משמעית**: שתי
--     המועמדות מתאימות (האחת בהתאמה מדויקת, השנייה דרך ברירות המחדל),
--     והקריאה נכשלת ב-`function is not unique` — כלומר משימת ה-cron של
--     004 מפסיקה לרוץ **בשקט**, עד שמישהו יקרא את יומן ה-cron.
--     ⚠️ `if exists` — הקובץ אידמפוטנטי גם בהרצה שנייה.
drop function if exists public.bk_retention_sweep(integer);

create or replace function public.bk_retention_sweep(
  p_days        integer default 30,
  p_keep        integer default 7,
  p_manual_days integer default 14
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_keys   text[] := public.bk_retention_keys();
  v_age    integer := 0;   -- מסלול א' — שגרה שעברה את חלון הימים
  v_cap    integer := 0;   -- מסלול ב' — שגרה שמעבר לתקרת העותקים
  v_manual integer := 0;   -- מסלול ג' — גיבוי ידני `pre-` שפג
begin
  if v_keys is null or cardinality(v_keys) = 0 then
    raise exception 'bk_retention_sweep: רשימת-ההיתר ריקה — מסרב לרוץ';
  end if;

  if exists (select 1 from unnest(v_keys) k
              where k like 'PRE\_%' or k like 'ORPHAN\_%' or k like 'pre-delete-%') then
    raise exception 'bk_retention_sweep: רשימת-ההיתר מכילה מפתח מוגן — מסרב לרוץ';
  end if;

  if p_days is null or p_days < 7 then
    raise exception 'bk_retention_sweep: חלון קצר מ-7 ימים — מסרב לרוץ';
  end if;

  if p_keep is null or p_keep < 1 then
    raise exception 'bk_retention_sweep: תקרת עותקים קטנה מ-1 — מסרב לרוץ';
  end if;

  if p_manual_days is null or p_manual_days < 7 then
    raise exception 'bk_retention_sweep: חלון ידני קצר מ-7 ימים — מסרב לרוץ';
  end if;

  -- ── א. שגרה שעברה את חלון הימים — ⛔ בדיוק כפי שהיה ב-004 ─────────────────
  delete from public.kv_backup
   where key = any (v_keys)
     and created_at < now() - make_interval(days => p_days);
  get diagnostics v_age = row_count;

  -- ── ב. תקרת עותקים — ⭐ החדש, ו⛔ **בנוסף** לא' ולא במקומה ─────────────────
  -- ⚠️ הסדר אינו מקרי: א' רץ ראשון, ולכן ב' סופר רק את מה ששרד את חלון
  --    הימים. ⛔ הסדר ההפוך היה סופר עותקים שכבר נמחקים ממילא, ומדווח
  --    ליומן מספר גדול מהאמת.
  -- ⚠️ **שובר-שוויון דטרמיניסטי — `id desc`** — שני עותקים של
  --    אותו מפתח יכולים לשאת אותה `created_at` (שתי כתיבות באותה שנייה),
  --    ובלי שובר-שוויון `row_number()` היה בוחר שרירותית **מי מבין
  --    השווים נמחק**. ⛔ `id` הוא identity עולה, ולכן «גדול יותר» = «חדש
  --    יותר», וההכרעה זהה בכל ריצה.
  -- ⚠️ **`created_at` ריק נשאר, ⛔ ובכיוון הבטוח**: ב-`<` הוא
  --    אינו נמחק (השוואה מול NULL אינה אמת), וב-`order by … desc` הוא
  --    ממוין ראשון (NULLS FIRST) ולכן נספר כ«חדש» ונשמר. ⛔ שורה שאין
  --    לתארך אינה נמחקת — זה ההפך מ«ספק ⇒ מוחקים».
  with ranked as (
    select id,
           row_number() over (partition by key
                              order by created_at desc, id desc) as rn
      from public.kv_backup
     where key = any (v_keys)
  )
  delete from public.kv_backup b
   using ranked r
   where b.id = r.id
     and r.rn > p_keep;
  get diagnostics v_cap = row_count;

  -- ── ג. גיבוי ידני בקידומת `pre-` — ⭐ החדש ────────────────────────────────
  -- ⛔ **אינו נוגע ברשימת-ההיתר** — ר' ההסבר הארוך למעלה. מפתח
  --    ידני אינו שגרה, אין לו תקרת עותקים, ⛔ והתפוגה שלו קצרה יותר:
  --    הוא נוצר כדי להגן על פעולה אחת, ואחרי שבועיים הפעולה כבר הוכרעה.
  delete from public.kv_backup
   where key like 'pre-%'
     and created_at < now() - make_interval(days => p_manual_days);
  get diagnostics v_manual = row_count;

  -- ── היומן — ⭐ שלושת המסלולים נספרים בנפרד ────────────────────────────────
  -- ⛔ מספר אחד מאוחד היה מסתיר איזה מסלול פעל: «נמחקו 40» אינו מבחין בין
  --    שגרה שהתיישנה לבין תקרה שנחתכה לבין גיבוי ידני שפג, ובדיוק ההבחנה
  --    הזו היא מה שיאפשר למדוד בעוד חודש אם המדיניות עובדת.
  -- ⚠️ **נרשם רק כשנמחק משהו בפועל** — התנהגות 004, בלי שינוי.
  if (v_age + v_cap + v_manual) > 0 then
    insert into public.sync_log (device_id, user_name, action, key, record_count, details)
    values ('pg_cron', null, 'retention', null, v_age + v_cap + v_manual,
            jsonb_build_object(
              'days',        p_days,
              'keep',        p_keep,
              'manual_days', p_manual_days,
              'keys',        cardinality(v_keys),
              'aged',        v_age,
              'capped',      v_cap,
              'manual',      v_manual));
  end if;

  return v_age + v_cap + v_manual;
end;
$$;


-- ───────────────────────────────────────────────────────────────────────────
-- 2. התזמון — אותה משימה, עם שלושת הערכים במפורש
-- ───────────────────────────────────────────────────────────────────────────
-- ⚠️ **הפקודה נכתבת עם שלושת הארגומנטים ולא נשענת על ברירות המחדל**
-- — `cron.job.command` הוא מה שרואים כשבודקים מה רץ במסד,
--    ⛔ ופקודה שמסתירה שני שלישים מהמדיניות מאחורי ברירת מחדל היא בדיוק
--    «מקור אמת שני» שמסתייג בשקט ביום שברירת המחדל תשתנה.
-- ⛔ `unschedule` לפני `schedule` — אידמפוטנטיות, ומניעת שתי
--    משימות שמריצות את אותה גריעה פעמיים.
-- ⚠️ 03:00 UTC נשאר כפי שהוא — ר' הנימוק ב-004.
do $$
begin
  if exists (select 1 from cron.job where jobname = 'bk_retention_daily') then
    perform cron.unschedule('bk_retention_daily');
  end if;
end;
$$;

select cron.schedule(
  'bk_retention_daily',
  '0 3 * * *',
  $$select public.bk_retention_sweep(30, 7, 14);$$
);


-- ───────────────────────────────────────────────────────────────────────────
-- 3. הרשאות — ⛔ החתימה השתנתה, ולכן ההרשאות נקבעות מחדש
-- ───────────────────────────────────────────────────────────────────────────
-- ⛔⛔ **זה הסעיף המסוכן בקובץ, וזו הסיבה שהוא כאן**: ב-Postgres
--     החתימה היא חלק מזהות הפונקציה, ולכן `bk_retention_sweep(integer,
--     integer, integer)` היא **פונקציה חדשה** — היא **אינה** יורשת את
--     ה-`revoke` שחל ב-004 על `bk_retention_sweep(integer)`. בלי הסעיף
--     הזה היא נולדת עם `execute` ל-`public`, כלומר פונקציית
--     `security definer` שנגישה כ-RPC לכל מי שמחזיק את המפתח הגלוי
--     שב-`index.html` — בדיוק החור ש-004 בא לסגור.
revoke all on function public.bk_retention_sweep(integer, integer, integer)
  from public, anon, authenticated;
grant execute on function public.bk_retention_sweep(integer, integer, integer)
  to service_role;

-- ⛔ ו-`kv_backup` עצמה נשארת `insert`+`select` בלבד לשני התפקידים
--    (כלל ברזל 10 סעיף 9) — הקובץ הזה **אינו** מעניק לה `delete`.
